#!/usr/bin/env python3
"""Compile the twelve exact 224x30 1-bit GLIDE sprites into immutable ROM.

Run from any directory.  Audio code is never involved in this conversion.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/glide-tunnel/frames"
DEST = ROOT / "vendor/etch-v1.88-source/firmware/fm1-native/rupture_tunnel_sprites.h"
WIDTH, HEIGHT, FRAMES = 224, 30, 12


def compile_frame(path: Path) -> list[list[int]]:
    with Image.open(path) as source:
        if source.size != (WIDTH, HEIGHT):
            raise ValueError(f"{path.name}: expected 224x30, got {source.size}")
        if source.convert("RGB").getcolors(WIDTH * HEIGHT + 1) is None:
            raise ValueError(f"{path.name}: color count unavailable")
        if any(c not in ((0, 0, 0), (255, 255, 255))
               for _, c in source.convert("RGB").getcolors(WIDTH * HEIGHT + 1)):
            raise ValueError(f"{path.name}: must be exactly black and white")
        bitmap = source.convert("1")
        return [
            [sum((1 << (7 - bit)) if bitmap.getpixel((x + bit, y)) else 0
                 for bit in range(8))
             for x in range(0, WIDTH, 8)]
            for y in range(HEIGHT)
        ]


def main() -> None:
    frames = [compile_frame(SOURCE / f"{frame:02}.png")
              for frame in range(FRAMES)]
    source = [
        "/* RUPTURE V1.97 GLIDE tunnel: twelve approved 224x30, 1-bit frames.",
        " * ROM-only static pixels (10,080 bytes), no runtime scaling or allocation.",
        " * Generated by tools/compile_glide_tunnel_v197.py from assets/glide-tunnel.",
        " */",
        "#ifndef RUPTURE_TUNNEL_SPRITES_H",
        "#define RUPTURE_TUNNEL_SPRITES_H",
        "#include <stdint.h>",
        "#define RU_TUNNEL_FRAMES 12u",
        "static const uint8_t ru_tunnel_sprites[RU_TUNNEL_FRAMES][30][28]={",
    ]
    for frame in frames:
        source.append(" {")
        for row in frame:
            source.append("  {" + ",".join(f"0x{byte:02x}" for byte in row) + "},")
        source.append(" },")
    source.extend(["};", "#endif", ""])
    DEST.write_text("\n".join(source))
    print(f"Generated {DEST}: {FRAMES} frames, {FRAMES * HEIGHT * WIDTH // 8:,} bytes ROM")


if __name__ == "__main__":
    main()
