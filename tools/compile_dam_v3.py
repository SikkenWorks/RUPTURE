#!/usr/bin/env python3
"""Converts supplied V3 user PNG pixels to lossless ROM bitmaps; no traced/rebuilt art."""
from pathlib import Path
from PIL import Image
from io import BytesIO
from hashlib import sha256
import json
root=Path(__file__).resolve().parents[1]
asset=root/'assets/dam-v3-frames/frames'
dst=root/'vendor/etch-v1.88-source/firmware/fm1-native/rupture_dam_sprites.h'
frames=[]
for i in range(1,21):
    p=asset/f'{i:02}.png'
    im=Image.open(p)
    assert im.mode=='1' and im.size==(224,30),(p, im.mode, im.size)
    # Pillow 1-bit mode is MSB-first, as is the existing native framebuffer.
    b=im.tobytes()
    assert len(b)==840
    frames.append(b)
head='''/* RUPTURE DAM V3: the 20 EXACT source 1-bit user PNGs, lossless, ROM only.
 * 224x30px MSB-first. UI blits 840 bytes at x=8, y=50 into existing canvas.
 * No runtime scaling, procedural water generation or audio work.
 * Generated by tools/compile_dam_v3.py; original PNGs in assets/dam-v3-frames/frames.
 * SPDX-License-Identifier: GPL-3.0-only
 */
#ifndef RUPTURE_DAM_SPRITES_H
#define RUPTURE_DAM_SPRITES_H
#include <stdint.h>
#define RU_DAM_X 8u
#define RU_DAM_Y 50u
#define RU_DAM_W 224u
#define RU_DAM_H 30u
#define RU_DAM_ROW_BYTES 28u
#define RU_DAM_NUM_FRAMES 20u
static const uint8_t ru_dam_sprites[RU_DAM_NUM_FRAMES][RU_DAM_H][RU_DAM_ROW_BYTES] = {\n'''
with dst.open('w') as f:
    f.write(head)
    for idx,b in enumerate(frames):
        f.write(f' /* Frame {idx} = {idx+1:02}.png */\n {{\n')
        for y in range(30):
            row=b[y*28:(y+1)*28]
            f.write('  {'+','.join('0x%02x'%c for c in row)+'}'+(',' if y<29 else '')+'\n')
        f.write(' }'+(',' if idx<19 else '')+'\n')
    f.write('};\n#endif\n')
(root/'assets/dam-v3-frames/native-frame-hashes.json').write_text(json.dumps({'frames':{f'{i+1:02}':sha256(b).hexdigest() for i,b in enumerate(frames)},'total_bytes':sum(map(len,frames))},indent=2)+'\n')
print('Generated',dst,'20 exact bitmaps',sum(map(len,frames)),'bytes')
