#!/usr/bin/env python3
"""Pack the 12 original 1-bit boot keyframes with 11 smooth in-betweens.

Uses byte-level PackBits-like RLE so the FM1 reuses its existing 7,200-byte
framebuffer. Source keyframes remain pixel-exact; the extra frames are built
deterministically using spatially ordered 1-bit temporal cross-dissolves.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
FRAMES = ROOT / "assets/boot-v2-signal-breach/frames"
TARGET = ROOT / "vendor/etch-v1.88-source/firmware/fm1-native/rupture_v2_signal_breach_sprites.h"
SOURCE_FRAMES = 12
FRAME_COUNT = 2 * SOURCE_FRAMES - 1
# Faster 28.6 fps first 22 frames, then a 1-second RUPTURE V2 brand hold.
# Nominal total is 1,770 ms versus 1,880 ms in V2.0.1.
DURATIONS_MS = (35,) * (FRAME_COUNT - 1) + (1000,)
FRAME_BYTES = 240 * 240 // 8

# Standard 8x8 Bayer ranks, used to replace half the differing pixels in the
# transition. Unchanged pixels pass through exactly, and no grayscale buffer
# or runtime blending is needed on the FM1.
BAYER_8 = (
    (0, 48, 12, 60, 3, 51, 15, 63),
    (32, 16, 44, 28, 35, 19, 47, 31),
    (8, 56, 4, 52, 11, 59, 7, 55),
    (40, 24, 36, 20, 43, 27, 39, 23),
    (2, 50, 14, 62, 1, 49, 13, 61),
    (34, 18, 46, 30, 33, 17, 45, 29),
    (10, 58, 6, 54, 9, 57, 5, 53),
    (42, 26, 38, 22, 41, 25, 37, 21),
)


def midpoint(a: bytes, b: bytes) -> bytes:
    """Dither a 50% transition in packed 1-bit order, without lossy originals."""
    if len(a) != FRAME_BYTES or len(b) != FRAME_BYTES:
        raise ValueError('Invalid source frame byte count')
    result = bytearray(FRAME_BYTES)
    for y in range(240):
        for byte_x in range(30):
            i = y * 30 + byte_x
            # Each packed input byte covers eight pixels; for each pixel use
            # the matching Bayer rank at this absolute display coordinate.
            mask = 0
            for bit in range(8):
                if BAYER_8[y & 7][bit] < 32:
                    mask |= 0x80 >> bit
            result[i] = (a[i] & ~mask) | (b[i] & mask)
    return bytes(result)


def encode(src: bytes) -> bytes:
    encoded = bytearray()
    at = 0
    while at < len(src):
        repeat = 1
        while at + repeat < len(src) and src[at + repeat] == src[at] and repeat < 128:
            repeat += 1
        if repeat >= 3:
            encoded.extend((0x80 | (repeat - 1), src[at]))
            at += repeat
            continue
        start = at
        at += repeat
        while at < len(src) and at - start < 128:
            next_repeat = 1
            while (at + next_repeat < len(src) and src[at + next_repeat] == src[at]
                   and next_repeat < 128):
                next_repeat += 1
            if next_repeat >= 3:
                break
            at += min(next_repeat, 128 - (at - start))
        encoded.append(at - start - 1)
        encoded.extend(src[start:at])
    return bytes(encoded)


def decode(data: bytes) -> bytes:
    out = bytearray()
    at = 0
    while at < len(data):
        tag = data[at]
        at += 1
        count = (tag & 0x7F) + 1
        if tag & 0x80:
            out.extend(bytes((data[at],)) * count)
            at += 1
        else:
            out.extend(data[at:at + count])
            at += count
    return bytes(out)


def generate() -> None:
    originals = []
    for frame in range(1, SOURCE_FRAMES + 1):
        path = FRAMES / f"frame-{frame:02}.png"
        with Image.open(path) as image:
            if image.mode != "1" or image.size != (240, 240):
                raise ValueError(f"Not exact 1-bit 240x240 art: {path}")
            raw = image.tobytes()
        if len(raw) != FRAME_BYTES:
            raise ValueError(f"Unexpected packed frame length: {path}")
        originals.append(raw)

    # 0, 2, 4, ... 22 are bit-for-bit the twelve supplied keyframes.
    frames = []
    for i, raw in enumerate(originals):
        frames.append(raw)
        if i + 1 < len(originals):
            frames.append(midpoint(raw, originals[i + 1]))
    assert len(frames) == FRAME_COUNT
    frame_data = []
    offsets = [0]
    for raw in frames:
        compressed = encode(raw)
        if decode(compressed) != raw:
            raise ValueError("Pack/unpack changed pixels")
        frame_data.append(compressed)
        offsets.append(offsets[-1] + len(compressed))
    packed = b"".join(frame_data)

    lines = [
        "/* SPDX-License-Identifier: GPL-3.0-only",
        " * RUPTURE V2 SIGNAL BREACH: 12 exact 1-bit keyframes + 11 transitions.",
        " * Generated by tools/compile_v2_signal_breach.py; do not hand-edit.",
        " * Byte RLE is lossless and uses the existing 7,200-byte UI framebuffer. */",
        "#pragma once",
        "#include <stdint.h>",
        f"#define RU_V2_BREACH_FRAMES {FRAME_COUNT}u",
        f"#define RU_V2_BREACH_DURATION_MS {sum(DURATIONS_MS)}u",
        f"#define RU_V2_BREACH_FRAME_BYTES {FRAME_BYTES}u",
        "static const uint16_t ru_v2_breach_ms[RU_V2_BREACH_FRAMES]={",
        " " + ",".join(f"{value}u" for value in DURATIONS_MS) + "};",
        "static const uint32_t ru_v2_breach_offsets[RU_V2_BREACH_FRAMES+1u]={",
        " " + ",".join(f"{offset}u" for offset in offsets) + "};",
        f"static const uint8_t ru_v2_breach_data[{len(packed)}]={{",
    ]
    for i in range(0, len(packed), 24):
        lines.append(" " + ",".join(f"0x{byte:02x}" for byte in packed[i:i + 24]) + ",")
    lines.extend([
        "};",
        "static inline void ru_v2_breach_decode(uint8_t *target,uint8_t frame){",
        " if(frame>=RU_V2_BREACH_FRAMES)frame=RU_V2_BREACH_FRAMES-1u;",
        " const uint8_t *p=ru_v2_breach_data+ru_v2_breach_offsets[frame];",
        " const uint8_t *end=ru_v2_breach_data+ru_v2_breach_offsets[frame+1u];",
        " uint32_t pos=0u;",
        " while(p<end && pos<RU_V2_BREACH_FRAME_BYTES){",
        "  uint8_t tag=*p++;uint32_t count=(uint32_t)(tag&127u)+1u;",
        "  if(count>RU_V2_BREACH_FRAME_BYTES-pos)count=RU_V2_BREACH_FRAME_BYTES-pos;",
        "  if(tag&128u){",
        "   uint8_t value=p<end?*p++:0u;",
        "   for(uint32_t i=0u;i<count;i++)target[pos++]=value;",
        "  }else{",
        "   for(uint32_t i=0u;i<count && p<end;i++)target[pos++]=*p++;",
        "  }",
        " }",
        " while(pos<RU_V2_BREACH_FRAME_BYTES)target[pos++]=0u;",
        "}",
        "static inline uint8_t ru_v2_breach_frame_at(uint32_t elapsed_ms){",
        " uint32_t elapsed_end=0u;",
        " for(uint8_t frame=0u;frame<RU_V2_BREACH_FRAMES;frame++){",
        "  elapsed_end+=(uint32_t)ru_v2_breach_ms[frame];",
        "  if(elapsed_ms<elapsed_end)return frame;",
        " }",
        " return RU_V2_BREACH_FRAMES-1u;",
        "}",
    ])
    TARGET.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"PASS {SOURCE_FRAMES} exact source frames + {FRAME_COUNT - SOURCE_FRAMES} "
          f"1-bit transitions: {FRAME_COUNT * FRAME_BYTES} -> {len(packed)} ROM bytes")


if __name__ == "__main__":
    generate()
