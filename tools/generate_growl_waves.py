#!/usr/bin/env python3
"""Build 7 band-limited GROWL oscillator tables from an analyzed harmonic profile.

The input reference is a musical video with a strong 36.7-Hz bass note.
Its sustained bass has unusually strong second, third and fourth harmonics,
with a weak fundamental. This reproduces that spectral *shape*, not samples
from the recording. No copyrighted audio is embedded in the firmware.
"""
import math
from pathlib import Path

OUT = (Path(__file__).resolve().parents[1] /
       "vendor/etch-v1.88-source/firmware/fm1-native/rupture_growl_waves.h")
SIZE = 256
LEVELS = (1, 2, 4, 8, 16, 32, 64)
# Approximate harmonic weights relative to harmonic four = 1.0.
# A finite bass fundamental is deliberately retained for keyboard tracking.
WEIGHTS = (0.15, 0.62, 0.86, 1.0, 0.19, 0.12, 0.16, 0.10,
           0.09, 0.08, 0.07, 0.06, 0.07, 0.055, 0.045, 0.055)


def harmonic(n):
    if n <= len(WEIGHTS):
        return WEIGHTS[n - 1]
    return 0.032 * (16.0 / n) ** 1.15


def table(partials):
    samples = []
    for i in range(SIZE):
        phase = math.tau * i / SIZE
        sample = 0.0
        for n in range(1, partials + 1):
            # Asymmetric harmonic phase relationships make the attack edgy.
            angle = (n % 5 - 2) * 0.37 + n * 0.07
            sample += harmonic(n) * math.sin(n * phase + angle)
        samples.append(sample)
    max_abs = max(abs(a) for a in samples)
    return [max(-27000, min(27000, round(a * 27000 / max_abs))) for a in samples]


def main():
    rows = [table(h) for h in LEVELS]
    lines = [
        "/* Generated by tools/generate_growl_waves.py. Do not edit by hand.",
        " * Harmonic approximation of the ROLI performance reference; no audio samples.",
        " * 256-point / 7-mip signed 16-bit table in program ROM; DSP uses integer math.",
        " * SPDX-License-Identifier: GPL-3.0-only */",
        "#ifndef RUPTURE_GROWL_WAVES_H",
        "#define RUPTURE_GROWL_WAVES_H",
        "#include <stdint.h>",
        "#include \"rupture_bandwaves.h\"",
        "static const int16_t ru_growl_waves[RU_WAVE_LEVELS][256] = {",
    ]
    for level, row in zip(LEVELS, rows):
        lines.append(" { /* up to %d harmonics */" % level)
        for index in range(0, SIZE, 16):
            lines.append("  " + ",".join(str(a) for a in row[index:index + 16]) +
                         ("," if index + 16 < SIZE else ""))
        lines.append(" },")
    lines[-1] = " }"
    lines += [
        "};",
        "/* Same Nyquist mip transitions as existing RUPTURE bandwaves. */",
        "static inline int32_t ru_growl_level_read(uint8_t level,uint32_t phase){",
        " uint8_t idx=(uint8_t)(phase>>24);",
        " uint32_t frac=(phase>>16)&255u;",
        " const int16_t *t=ru_growl_waves[level];",
        " int32_t a=t[idx];",
        " return a+(((int32_t)t[(uint8_t)(idx+1u)]-a)*(int32_t)frac>>8);",
        "}",
        "static inline int32_t ru_growl_read(uint32_t phase,uint32_t increment){",
        " uint8_t level=ru_wave_band(increment);",
        " int32_t now=ru_growl_level_read(level,phase);",
        " if(level){",
        "  uint32_t threshold=0x7fffffffu>>level;",
        "  uint32_t fade_range=threshold>>3;",
        "  if(increment>threshold-fade_range && increment<=threshold){",
        "   uint32_t mix=(threshold-increment)>>(20u-level);",
        "   if(mix>256u)mix=256u;",
        "   int32_t old=ru_growl_level_read((uint8_t)(level-1u),phase);",
        "   now=((now*(int32_t)mix)+(old*(int32_t)(256u-mix)))>>8;",
        "  }",
        " }",
        " return now;",
        "}",
        "#endif",
    ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf8")
    print("Generated", OUT, "(%d bytes)" % OUT.stat().st_size)


if __name__ == "__main__":
    main()
