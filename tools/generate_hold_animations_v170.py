#!/usr/bin/env python3
"""Generate the RUPTURE V1.70 ENV dust-settle and LFO debris-loop sprite art.

Both effects use 8 pre-rendered, 224x30, pure 1-bit ROM frames derived from
V1.56 panel frame 13. Nothing is calculated in the ISR or the DSP callback.
The original 20 open/release frames stay byte-identical and remain the only
art used during the open/close transitions.
"""
from pathlib import Path
from PIL import Image, ImageDraw
import hashlib, json
ROOT=Path(__file__).resolve().parents[1]
ORIGINAL=ROOT/'assets/panel-animations-v156'
OUTPUT=ROOT/'assets/panel-hold-v170'
HEADER=ROOT/'vendor/etch-v1.88-source/firmware/fm1-native/rupture_hold_sprites.h'
N=8; W=224; H=30

def base(kind):
    p=ORIGINAL/kind/'13.png'  # existing frame index 12, fully open
    im=Image.open(p).convert('1')
    assert im.size==(W,H), p
    return im

def pixel_if(im,xy,baseval,paint):
    x,y=xy
    if 0<=x<W and 0<=y<H and im.getpixel((x,y))==baseval:
        paint.point((x,y),fill=255 if baseval==0 else 0)

def dot_cloud(im,x,y,radius,shade,seed):
    """Temporary single-bit dust puff, irregular with a dithered contour."""
    d=ImageDraw.Draw(im)
    for yy in range(-radius,radius+1):
        for xx in range(-radius*2,radius*2+1):
            if (xx*xx*2+yy*yy*7)>radius*radius*8:continue
            if ((xx*13+yy*7+seed*17)&7)>(shade+2):continue
            ax=x+xx; ay=y+yy
            if not (1<=ay<H-2 and 66<=ax<=165):continue
            # Dust is a bright stipple against the dark rupture, or a dark
            # stipple on the bright wall. Never touch outer mural pixels.
            old=im.getpixel((ax,ay))
            if old==0 and (xx+yy+seed)%3:pixel_if(im,(ax,ay),0,d)
            elif old==255 and ((xx*3+yy+seed)&3)==0:pixel_if(im,(ax,ay),255,d)

def make_env(i):
    im=base('env');d=ImageDraw.Draw(im)
    # Seven short in-between frames: the smoke descends toward the rubble,
    # disperses, and vanishes. Frame 8 is the original steady aftermath.
    if i==7:return im
    opacity=[7,7,6,5,4,3,1][i]
    centers=[(90,10),(105,6),(129,7),(143,9),(118,13),(85,15),(153,16)]
    for j,(x,y) in enumerate(centers):
        if i>=4 and (j+i)%3==0:continue
        if i>=6 and j>1:continue
        xx=x+((i*(1 if j%2 else -1))//2)
        yy=min(26,y+i*2 + (j%3))
        radius=3 if i<3 else 2 if i<5 else 1
        dot_cloud(im,xx,yy,radius,opacity-1,j+i*2)
    # A low scattering of smoke/dust gathers around the rubble line before
    # it settles. The count is deliberately monotonically reduced.
    count=[18,16,13,10,7,4,2][i]
    for j in range(count):
        x=80+(j*37+17)%75
        y=min(26,17+(j*5+i*2)%10)
        pixel_if(im,(x,y),0 if (j&1) else 255,d)
    return im

def make_lfo(i):
    im=base('lfo');d=ImageDraw.Draw(im)
    # Four independent streams of small white rock fragments tumble through
    # the dark hole. Their phases are staggered; the 8-frame loop repeats
    # seamlessly as an endless shower, rather than oscillating up and down.
    streams=[(92,0,1),(149,2,-1),(107,4,1),(137,6,-1),
             (122,1,0),(98,5,1),(144,7,-1),(114,3,0)]
    for j,(x0,offset,lean) in enumerate(streams):
        age=(i+offset)%N
        y=6+age*3
        x=x0+lean*age*2+(j%2)
        if y>27:continue
        # Bright, angular 1-bit pebbles, not smooth particles.
        size=3 if j%3==0 else 2
        for oy in range(size):
            for ox in range(size+1):
                if (ox==size and oy>0) or (ox==0 and oy==size-1):continue
                pixel_if(im,(x+ox,y+oy),0,d)
        # A staggered finer fleck falls slightly behind each rock.
        if age>=2:pixel_if(im,(x-lean,y-4),0,d)
    return im

def packed(im):
    assert im.mode=='1' and im.size==(W,H)
    blob=bytes(sum((1<<(7-k)) if im.getpixel((x+k,y)) else 0 for k in range(8))
               for y in range(H) for x in range(0,W,8))
    assert len(blob)==W*H//8
    return blob

def emit_header(collection):
    out=['/* RUPTURE V1.70: eight ROM-only ENV settling and LFO debris-loop sprites.',
         ' * 224x30 1-bit. Original V1.56 opening and release artwork unchanged.',
         ' * All animation operates exclusively in the UI rendering loop.',
         ' * Generated by tools/generate_hold_animations_v170.py.',
         ' * SPDX-License-Identifier: GPL-3.0-only */',
         '#ifndef RUPTURE_HOLD_SPRITES_H','#define RUPTURE_HOLD_SPRITES_H',
         '#include <stdint.h>','#define RU_HOLD_FRAMES 8u']
    for kind,images in collection.items():
        out.append(f'static const uint8_t ru_{kind}_hold_sprites[RU_HOLD_FRAMES][30][28]={{')
        for im in images:
            b=packed(im)
            out.append(' {')
            for y in range(H):
                out.append('  {'+','.join('0x%02x'%v for v in b[y*28:(y+1)*28])+'},')
            out.append(' },')
        out.append('};')
    out.append('#endif')
    HEADER.write_text('\n'.join(out)+'\n')

def main():
    images={'env':[make_env(i) for i in range(N)],'lfo':[make_lfo(i) for i in range(N)]}
    audit={'generator':'tools/generate_hold_animations_v170.py','source_frame':'V1.56 env/lfo 13.png',
           'width':W,'height':H,'frames':N,'sha256':{}}
    for kind,group in images.items():
        target=OUTPUT/kind;target.mkdir(parents=True,exist_ok=True)
        audit['sha256'][kind]=[]
        for i,im in enumerate(group):
            path=target/f'{i+1:02}.png';im.save(path)
            audit['sha256'][kind].append(hashlib.sha256(packed(im)).hexdigest())
        # Loop and hold previews: only source data, nearest-neighbor 4x
        frames=[im.resize((W*4,H*4),Image.Resampling.NEAREST).convert('P') for im in group]
        if kind=='env':frames+=frames[-1:]*8
        frames[0].save(OUTPUT/f'{kind}-preview.gif',save_all=True,append_images=frames[1:],
                       duration=125 if kind=='lfo' else 150,loop=0,disposal=2,optimize=False)
    from PIL import ImageOps
    sheet=Image.new('RGB',(W*4*2,H*4*N+N*2),(32,32,32))
    for j,kind in enumerate(('env','lfo')):
        for i,im in enumerate(images[kind]):
            sheet.paste(im.convert('RGB').resize((W*4,H*4),Image.Resampling.NEAREST),(j*W*4,i*(H*4+2)))
    sheet.save(OUTPUT/'ENV-SETTLE-LFO-DIRT-CONTACT-4X.png')
    OUTPUT.mkdir(parents=True,exist_ok=True)
    (OUTPUT/'ANIMATION-MANIFEST.json').write_text(json.dumps(audit,indent=2)+'\n')
    emit_header(images)
    print('Generated 8 ENV settle + 8 LFO falling-debris frames, pure 1-bit 224x30; header',HEADER.stat().st_size,'bytes')
if __name__=='__main__':main()
