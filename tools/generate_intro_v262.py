#!/usr/bin/env python3
"""Pack the supplied 240x240 startup PNGs into LCD-ready frames."""
from pathlib import Path
from zipfile import ZipFile
from PIL import Image
import re
import sys


def pack(data):
    """Literal runs and backward copies, with independent decode per block."""
    recent = {}
    output = bytearray()
    literal = bytearray()

    def flush():
        if literal:
            output.append(len(literal) - 1)
            output.extend(literal)
            literal.clear()

    pos = 0
    while pos < len(data):
        key = data[pos:pos + 3]
        previous = recent.get(key)
        length = 0
        if previous is not None and len(key) == 3:
            length = 3
            while length < min(130, len(data) - pos) and data[previous + length] == data[pos + length]:
                length += 1
            flush()
            output.extend((128 | (length - 3), (pos - previous) >> 8, (pos - previous) & 255))
        else:
            literal.append(data[pos])
            if len(literal) == 128:
                flush()
            length = 1
        for index in range(pos, pos + length):
            recent[data[index:index + 3]] = index
        pos += length
    flush()
    return bytes(output)


def unpack(data):
    output = bytearray()
    pos = 0
    while pos < len(data):
        token = data[pos]
        pos += 1
        if token < 128:
            end = pos + token + 1
            output.extend(data[pos:end])
            pos = end
        else:
            distance = int.from_bytes(data[pos:pos + 2], 'big')
            pos += 2
            for _ in range((token & 127) + 3):
                output.append(output[-distance])
    return output


def array(name, values, dtype):
    lines = [f'static const {dtype} {name}[] = {{']
    for pos in range(0, len(values), 16):
        lines.append(' ' + ', '.join(str(v) for v in values[pos:pos + 16]) + ',')
    return '\n'.join(lines + ['};', ''])


def main():
    blocks = {}
    packed = bytearray()

    def offset(raw):
        if raw not in blocks:
            compressed = pack(raw)
            assert unpack(compressed) == raw
            blocks[raw] = len(packed)
            packed.extend(compressed)
        return blocks[raw]

    logo = []
    mono = []
    palettes = []
    rows = {}
    with ZipFile(sys.argv[1]) as archive:
        for scene, pattern, expected in (
            (1, r'Intro1/frame-(\d+)\.png', range(1, 9)),
            (2, r'Intro2/frame_(\d+)\.png', range(135)),
        ):
            names = {int(match[1]): name for name in archive.namelist()
                     if (match := re.fullmatch(pattern, name))}
            assert sorted(names) == list(expected)
            for index in expected:
                with Image.open(archive.open(names[index])) as image:
                    assert image.size == (240, 240)
                    if scene == 1:
                        indexed = image.convert('P') if image.mode != 'P' else image
                        pixels = indexed.tobytes()
                        palette = indexed.getpalette()
                        palette += [0] * (768 - len(palette))
                        for i in range(0, 768, 3):
                            red, green, blue = palette[i:i + 3]
                            rgb = ((red >> 3) << 11) | ((green >> 2) << 5) | (blue >> 3)
                            palettes.append(((rgb & 255) << 8) | (rgb >> 8))
                        logo.extend(offset(pixels[i:i + 11520])
                                    for i in range(0, len(pixels), 11520))
                    else:
                        assert image.mode == '1'
                        pixels = image.tobytes()
                        row_ids = bytearray()
                        for i in range(0, len(pixels), 30):
                            row = pixels[i:i + 30]
                            row_ids.extend(rows.setdefault(row, len(rows)).to_bytes(2, 'little'))
                        mono.append(offset(bytes(row_ids)))

    out = Path(__file__).resolve().parents[1] / 'vendor/etch-v1.88-source/firmware/fm1-native/rupture_intro_frames.h'
    out.write_text('/* Generated by tools/generate_intro_v262.py. */\n'
                   '#ifndef RUPTURE_INTRO_FRAMES_H\n#define RUPTURE_INTRO_FRAMES_H\n'
                   '#include <stdint.h>\n'
                   + array('ru_intro_logo_offsets', logo, 'uint32_t')
                   + array('ru_intro_mono_offsets', mono, 'uint32_t')
                   + array('ru_intro_palettes', palettes, 'uint16_t')
                   + array('ru_intro_rows', b''.join(rows), 'uint8_t')
                   + array('ru_intro_data', packed, 'uint8_t')
                   + '#endif\n')
    print(f'{len(logo) // 5} RGB565 frames + {len(mono)} monochrome frames, {len(packed)} packed bytes')


if __name__ == '__main__':
    main()
