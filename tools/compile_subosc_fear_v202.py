#!/usr/bin/env python3
"""Compile the two exact 224x30 1-bit SUB OSC fear animations to ROM.

All 16 original PNGs per oscillator are packed unchanged. No runtime image
scaling, allocations, sampling or audio-ISR processing is required.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/subosc-v2"
TARGET = ROOT / "vendor/etch-v1.88-source/firmware/fm1-native/rupture_subosc_fear_sprites.h"
FOLDERS = ("RUPTURE-V2-SUBOSC1-FEAR", "RUPTURE-V2-SUBOSC2-NORMAL")
WIDTH, HEIGHT, FRAMES = 224, 30, 16


def load_frame(path: Path) -> bytes:
    with Image.open(path) as image:
        if image.size != (WIDTH, HEIGHT) or image.mode != '1':
            raise ValueError(f"Expected exact 224x30 1-bit sprite: {path}")
        raw = image.tobytes()
    if len(raw) != WIDTH * HEIGHT // 8:
        raise ValueError(f"Unexpected packed pixels: {path}")
    return raw


def main() -> None:
    lines = [
        "/* RUPTURE V2.0.2: source-exact 224x30 SUB OSC 1 + 2 fear sprites.",
        " * Generated by tools/compile_subosc_fear_v202.py; do not edit.",
        " * 16 frames per oscillator, ROM-only, 1 bit/pixel, no audio work. */",
        "#ifndef RUPTURE_SUBOSC_FEAR_SPRITES_H",
        "#define RUPTURE_SUBOSC_FEAR_SPRITES_H",
        "#include <stdint.h>",
        "#define RU_SUB_FEAR_FRAMES 16u",
        "static const uint8_t ru_sub_fear_sprites[2][RU_SUB_FEAR_FRAMES][30][28]={",
    ]
    for folder in FOLDERS:
        lines.append(" {")
        for frame in range(1, FRAMES + 1):
            raw = load_frame(SOURCE / folder / "frames-224x30" / f"frame-{frame:02}.png")
            lines.append("  {")
            for y in range(HEIGHT):
                row = raw[y * 28:(y + 1) * 28]
                lines.append("   {" + ",".join(f"0x{byte:02x}" for byte in row) + "},")
            lines.append("  },")
        lines.append(" },")
    lines.extend(["};", "#endif", ""])
    TARGET.write_text("\n".join(lines), encoding="utf-8")
    print(f"PASS 2 x {FRAMES} original 224x30 1-bit frames -> {TARGET}")


if __name__ == '__main__':
    main()
