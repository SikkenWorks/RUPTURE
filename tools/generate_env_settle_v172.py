#!/usr/bin/env python3
"""Regenerate only RUPTURE ENV dust settling sprites, 1-bit, 224x30.

V1.56's 20 opening/closing frames and V1.70's eight LFO debris-loop
sprites remain byte-identical. Final ENV hold sprite equals the original
fully-open wall, without airborne smoke, and is not itself a loop.
"""
from pathlib import Path
from PIL import Image, ImageDraw
import hashlib, json, re
root=Path(__file__).resolve().parents[1]
base=Image.open(root/'assets/panel-animations-v156/env/13.png').convert('1')
old=root/'assets/panel-hold-v170/lfo'
out=root/'assets/panel-hold-v172/env';out.mkdir(parents=True,exist_ok=True)
header=root/'vendor/etch-v1.88-source/firmware/fm1-native/rupture_hold_sprites.h'
W,H=224,30
assert base.size==(W,H)

def packed(im):
 return bytes(sum((1<<(7-b)) if im.getpixel((x+b,y)) else 0 for b in range(8)) for y in range(H) for x in range(0,W,8))

def smoke(im,cx,cy,rx,ry,phase):
 """Alternating black/white contour and stipple masks for visible smoke wisps."""
 d=ImageDraw.Draw(im)
 for dy in range(-ry,ry+1):
  for dx in range(-rx,rx+1):
   if dx*dx*(ry*ry)+dy*dy*(rx*rx)>rx*rx*ry*ry:continue
   x,y=cx+dx,cy+dy
   if not(75<=x<=155 and 3<=y<=26):continue
   if (dx*11+dy*7+phase*5)%9==0:continue
   # white mists in dark breach, dark veins against white wall.
   original=base.getpixel((x,y))
   if original==0 and ((dx+3*dy+phase)&3)!=0:d.point((x,y),fill=255)
   if original==255 and ((5*dx+dy+phase)&3)==0:d.point((x,y),fill=0)

def pebble(im,x,y,size):
 d=ImageDraw.Draw(im)
 for dy in range(size):
  for dx in range(size+1):
   px,py=x+dx,y+dy
   if not(75<=px<=155 and 4<=py<=26):continue
   if (dx,dy)==(0,size-1):continue
   d.point((px,py),fill=255 if base.getpixel((px,py))==0 else 0)

frames=[]
for i in range(8):
 im=base.copy()
 if i<7:
  # Large first puffs visibly dissipate *downwards*, never rise/loop.
  rx=[9,8,7,6,5,3,1][i];ry=[5,5,4,4,3,2,1][i]
  for j,(x,y) in enumerate([(92,6),(113,4),(134,7),(102,13),(143,12)]):
   if i>=5 and j%2==1:continue
   if i>=6 and j>1:continue
   smoke(im,x+(j%2)*i//2,y+i*2,rx,ry,j+i)
  # Falling stones shrink and join existing rubble at the bottom.
  for j in range(max(0,7-i)):
   px=83+(j*19+11)%67+(i//2 if j%2 else -i//2)
   py=min(25,7+((j*7)%10)+i*3)
   pebble(im,px,py,3 if i<3 and j%3==0 else 2 if i<5 else 1)
 frames.append(im)
 im.save(out/f'{i+1:02}.png')
# Keep all LFO sprite bytes from V1.70, only regen ENV ROM rows.
rom=header.read_text();start=rom.index('static const uint8_t ru_env_hold_sprites[')
end=rom.index('static const uint8_t ru_lfo_hold_sprites[')
lines=['static const uint8_t ru_env_hold_sprites[RU_HOLD_FRAMES][30][28]={']
for im in frames:
 b=packed(im);lines+=[' {']
 for y in range(H):lines.append('  {'+','.join('0x%02x'%n for n in b[y*28:(y+1)*28])+'},')
 lines+=[' },']
lines.append('};')
rom=rom[:start]+'\n'.join(lines)+'\n'+rom[end:]
rom=rom.replace('RUPTURE V1.70: eight ROM-only ENV settling','RUPTURE V1.72: eight ROM-only ENV settling').replace(' * Generated by tools/generate_hold_animations_v170.py.',' * ENV generated by tools/generate_env_settle_v172.py; LFO from V1.70.')
header.write_text(rom)
contact=Image.new('RGB',(896,480),'#333')
for i,im in enumerate(frames):contact.paste(im.resize((448,120),Image.Resampling.NEAREST).convert('RGB'),(i%2*448,i//2*120))
contact.save(root/'assets/panel-hold-v172/ENV-8-FRAMES-CONTACT.png')
preview=[im.resize((896,120),Image.Resampling.NEAREST).convert('P') for im in frames]
preview[0].save(root/'assets/panel-hold-v172/ENV-NOTE-HOLD-PREVIEW.gif',save_all=True,append_images=preview[1:]+[preview[-1]]*10,duration=150,loop=0,disposal=2)
(root/'assets/panel-hold-v172/ANIMATION-MANIFEST.json').write_text(json.dumps({'version':'1.72','size':[224,30],'frames':8,'ENV':'one-way smoke/pebble settling, last frame static (wall shake from UI blitter)','LFO':'unchanged V1.70 sprites','sha256':[hashlib.sha256(packed(im)).hexdigest() for im in frames]},indent=2)+'\n')
assert packed(frames[-1])==packed(base)
print('Generated 8 ENV PNGs, unchanged original 20 opening/closing frames and LFO sprites')
